#!/usr/bin/env node
// Build-time only: mechanically copies the two shared source-of-truth assets
// that live outside site/ (so a GitHub Pages deploy of site/ alone is fully
// self-contained) without hand-forking either one:
//   ../app/matcher.js       -> site/vendor/matcher.js   (canonical matcher,
//                              byte-identical copy, never edited here)
//   ../app/i18n/*.json      -> site/i18n/*.json          (12-language catalog;
//                              app/i18n/ remains the source of truth — see
//                              the note this script prepends to each file)
//
// Usage:  node site/build-assets.mjs
// Re-run after any change to app/matcher.js or app/i18n/*.json.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

function copyMatcher() {
  const src = path.join(ROOT, 'app/matcher.js');
  const destDir = path.join(__dirname, 'vendor');
  const dest = path.join(destDir, 'matcher.js');
  fs.mkdirSync(destDir, { recursive: true });
  const header =
    '// AUTO-COPIED verbatim from app/matcher.js by site/build-assets.mjs.\n' +
    '// DO NOT EDIT THIS FILE DIRECTLY — edit app/matcher.js (the canonical\n' +
    '// matcher, shared with the server\'s Python port) and re-run the build\n' +
    '// script. This copy exists only so a GitHub Pages deploy of site/ alone\n' +
    '// is self-contained; it is never a fork.\n';
  const body = fs.readFileSync(src, 'utf8');
  fs.writeFileSync(dest, header + body);
  console.log('Wrote', dest);
}

function copyI18n() {
  const srcDir = path.join(ROOT, 'app/i18n');
  const destDir = path.join(__dirname, 'i18n');
  fs.mkdirSync(destDir, { recursive: true });
  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.json'));
  for (const file of files) {
    const data = JSON.parse(fs.readFileSync(path.join(srcDir, file), 'utf8'));
    // app/i18n/*.json remains the source of truth for every key that exists
    // there; site/i18n/*.json may carry additional client-only UI-string
    // keys added on top (share, accounts, listen, levels, errors, etc. —
    // see docs/BUILD-PLAN.md Phase 3 / WP-D) that this copy step preserves
    // by merging rather than overwriting when the destination already has
    // extra keys the source doesn't.
    const destPath = path.join(destDir, file);
    let merged = data;
    if (fs.existsSync(destPath)) {
      try {
        const existing = JSON.parse(fs.readFileSync(destPath, 'utf8'));
        merged = { ...existing, ...data }; // source of truth wins on shared keys
      } catch (_) { /* corrupt/missing destination copy: just overwrite */ }
    }
    fs.writeFileSync(destPath, JSON.stringify(merged, null, 2) + '\n');
  }
  console.log(`Wrote ${files.length} catalogs to ${destDir}`);
}

copyMatcher();
copyI18n();
